import { existsSync } from 'fs';
import { FileLoader, FileReader, NanoObject } from '@nano-app/core';
import type { DatabaseConfig } from '../types/database';
import type { PrismaPg } from '@prisma/adapter-pg';
import { getDir } from '../../const';

export default abstract class Database {
  private static oAdapter?: PrismaPg;

  /** Mounted clients, by name */
  private static oClients: NanoObject = {};

  /** Initializes the Database client */
  public static async init(): Promise<void> {
    // Checks the DATABASE_URL is defined
    const sUrl = process.env.DATABASE_URL;
    if (!sUrl) {
      throw new Error('[nano-app] [ERROR] The DATABASE_URL environment variable is not defined.');
    }

    // Create the adapter (imported only when needed)
    const { PrismaPg } = await import('@prisma/adapter-pg');
    this.oAdapter = new PrismaPg({ connectionString: sUrl });
  }

  /** Gets a client by name */
  // any: the Prisma client is generated per plugin, unknown to the framework
  public static get(sName: string): any {
    return this.oClients[sName];
  }

  /** Mounts a generated Prisma client */
  // any: the Prisma client is generated per plugin, unknown to the framework
  public static async mount(sName: string, { schemaPath }: DatabaseConfig): Promise<any> {
    // Fail if trying to mount a client that already exists
    if (this.get(sName)) {
      throw new Error(`[nano-app] [ERROR] The database "${sName}" is already mounted.`);
    }

    // Every client is generated by nano-app, named as its plugin
    const sClientPath = `${process.cwd()}/.nano-app/prisma-clients/${sName}/generated/client.ts`;
    if (!existsSync(sClientPath)) {
      throw new Error(
        `[nano-app] [ERROR] The prisma client of "${sName}" does not exist. Run \`npx nano-app generate ${sName}\`.`,
      );
    }

    // Creates the adapter when no consumer database did
    if (!this.oAdapter) await this.init();

    // Loads the client and validates the schema
    const PrismaClient = await FileLoader.findPrismaClient(sClientPath, schemaPath);

    // Plugins' schemas (in the framework's plugins/) use only nano_*; the consumer's never do
    const bIsPlugin = schemaPath.startsWith(getDir('plugins'));
    const sDeclared =
      FileReader.loadFile(schemaPath)
        .replace(/\/\/.*$/gm, '')
        .match(/datasource\s+\w+\s*\{[^}]*schemas\s*=\s*\[([^\]]*)\]/s)?.[1] ?? '';
    const aSchemas = [...sDeclared.matchAll(/["']([^"']+)["']/g)].map(([, sSchema]) => sSchema);
    if (
      bIsPlugin
        ? !aSchemas.length || aSchemas.some(sSchema => !sSchema.startsWith('nano_'))
        : aSchemas.some(sSchema => sSchema.startsWith('nano_'))
    ) {
      throw new Error(
        `[nano-app] [ERROR] ${schemaPath}: ${bIsPlugin ? 'a plugin declares only nano_* schemas' : 'the nano_* schemas are reserved for plugins'}.`,
      );
    }

    let oClient;
    try {
      // Instantiates it with the pg adapter
      oClient = new PrismaClient({ adapter: this.oAdapter });
    } catch (oError: any) {
      // any: anything can be thrown
      throw new Error(
        `[nano-app] [ERROR] Cannot instantiate the database "${sName}" from ${sClientPath}: ${oError?.message ?? oError}`,
      );
    }

    // A plugin's tables are pushed in development: checks each model can be read
    if (bIsPlugin) {
      for (const [, sModel] of FileReader.loadFile(schemaPath).matchAll(/^\s*model\s+(\w+)/gm)) {
        await oClient[sModel[0].toLowerCase() + sModel.slice(1)]
          .findFirst()
          // any: anything can be thrown
          .catch((oError: any) => {
            // Last line of Prisma's message: the table that is missing
            const sReason = String(oError?.message ?? oError)
              .trim()
              .split('\n')
              .pop();
            throw new Error(
              `[nano-app] [ERROR] The database "${sName}" is not ready: ${sReason} Run \`npx nano-app push ${sName}\`.`,
            );
          });
      }
    }

    // Mounts the client
    this.oClients[sName] = oClient;
    console.log(`[nano-app] [INFO] Database "${sName}" mounted`);

    return oClient;
  }
}
